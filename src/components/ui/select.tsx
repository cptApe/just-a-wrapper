'use client';

import * as SelectPrimitive from '@radix-ui/react-select';
import * as React from 'react';
import { IconCheck, IconChevronDown, IconChevronUp } from '@/components/icons';
import { cn } from '@/lib/utils';
import { FLOATING_EDGE_GAP } from './lib/floating';

export const Select = SelectPrimitive.Root;
export const SelectValue = SelectPrimitive.Value;

export const SelectTrigger = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Trigger>
>(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Trigger
    ref={ref}
    className={cn(
      'flex h-9 max-sm:min-h-9 max-sm:text-body w-full items-center justify-between gap-2 rounded-md bg-alpha-6 px-3 py-1',
      'text-title-card text-foreground placeholder:text-muted-foreground',
      'transition-[box-shadow] duration-150 ease-[var(--ease-out)]',
      'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-1 focus-visible:ring-offset-background',
      'disabled:cursor-not-allowed disabled:opacity-50',
      '[&>span]:line-clamp-1',
      className,
    )}
    {...props}
  >
    {children}
    <SelectPrimitive.Icon asChild>
      <IconChevronDown className="size-4 text-muted-foreground" />
    </SelectPrimitive.Icon>
  </SelectPrimitive.Trigger>
));
SelectTrigger.displayName = 'SelectTrigger';

