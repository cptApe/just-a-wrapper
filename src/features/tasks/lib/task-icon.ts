/** Icons store either a name or a name:color pair. */
export function decodeTaskIcon(value?: string | null) {
  const [rawName, rawColor] = (value ?? '').split(':');
  return {
    name: TASK_ICON_NAMES.find((name) => name === rawName) ?? null,
    color: TASK_ICON_COLORS.find((color) => color === rawColor) ?? null,
  };
}
export function isTaskIcon(value: string): boolean {
  const parts = value.split(':');
  const parsed = decodeTaskIcon(value);
  return (
    parsed.name !== null && (parts.length === 1 || (parts.length === 2 && parsed.color !== null))
  );
}
